/**
 * Build worker/src/airport-cities.js from OurAirports airports.csv.
 *
 * Usage: node scripts/generate-airport-city-map.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const OURAIRPORTS_CSV_URL =
  "https://davidmegginson.github.io/ourairports-data/airports.csv";
export const OURAIRPORTS_COUNTRIES_CSV_URL =
  "https://davidmegginson.github.io/ourairports-data/countries.csv";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..");
const defaultOutPath = join(repoRoot, "worker/src/airport-cities.js");

/** Parse one CSV line respecting double-quoted fields. */
export function parseCsvLine(line) {
  const fields = [];
  let cur = "";
  let inQuotes = false;
  for (let i = 0; i < line.length; i += 1) {
    const ch = line[i];
    if (inQuotes) {
      if (ch === '"') {
        if (line[i + 1] === '"') {
          cur += '"';
          i += 1;
        } else {
          inQuotes = false;
        }
      } else {
        cur += ch;
      }
      continue;
    }
    if (ch === '"') {
      inQuotes = true;
      continue;
    }
    if (ch === ",") {
      fields.push(cur);
      cur = "";
      continue;
    }
    cur += ch;
  }
  fields.push(cur);
  return fields;
}

/**
 * @param {string} city
 * @param {string} isoCountry
 * @param {string} isoRegion
 * @param {Record<string, string>} countryNames
 */
export function formatAirportPlace(
  city,
  isoCountry,
  isoRegion,
  countryNames = {},
) {
  const place = String(city || "").trim();
  const country = String(isoCountry || "").trim().toUpperCase();
  const region = String(isoRegion || "").trim().toUpperCase();
  if (country === "US" && /^US-[A-Z]{2}$/.test(region)) {
    return `${place}, ${region.slice(3)}`;
  }
  if (country !== "US" && countryNames[country]) {
    return `${place}, ${String(countryNames[country]).trim()}`;
  }
  return place;
}

/**
 * @param {string} csvText
 * @param {Record<string, string>} [countryNames]
 * @returns {{ map: Record<string, string>, conflicts: string[], skippedNoMunicipality: number, rowCount: number }}
 */
export function buildMapFromCsv(csvText, countryNames = {}) {
  const lines = csvText.trim().split(/\r?\n/);
  if (lines.length < 2) {
    return {
      map: {},
      conflicts: [],
      skippedNoMunicipality: 0,
      rowCount: 0,
    };
  }

  const header = parseCsvLine(lines[0]);
  const idx = {
    municipality: header.indexOf("municipality"),
    iata: header.indexOf("iata_code"),
    icao: header.indexOf("icao_code"),
    isoCountry: header.indexOf("iso_country"),
    isoRegion: header.indexOf("iso_region"),
  };
  if (idx.municipality < 0 || idx.iata < 0 || idx.icao < 0) {
    throw new Error("airports.csv missing required columns");
  }

  /** @type {Map<string, Set<string>>} */
  const codeToCities = new Map();
  let skippedNoMunicipality = 0;
  let rowCount = 0;

  for (let i = 1; i < lines.length; i += 1) {
    const line = lines[i];
    if (!line.trim()) continue;
    rowCount += 1;
    const cols = parseCsvLine(line);
    const municipality = String(cols[idx.municipality] || "").trim();
    if (!municipality) {
      skippedNoMunicipality += 1;
      continue;
    }

    const codes = [];
    const iata = String(cols[idx.iata] || "").trim().toUpperCase();
    const icao = String(cols[idx.icao] || "").trim().toUpperCase();
    if (iata) codes.push(iata);
    if (icao) codes.push(icao);
    if (codes.length === 0) continue;
    const place = formatAirportPlace(
      municipality,
      cols[idx.isoCountry],
      cols[idx.isoRegion],
      countryNames,
    );

    for (const code of codes) {
      let cities = codeToCities.get(code);
      if (!cities) {
        cities = new Set();
        codeToCities.set(code, cities);
      }
      cities.add(place);
    }
  }

  /** @type {Record<string, string>} */
  const map = Object.create(null);
  /** @type {string[]} */
  const conflicts = [];

  for (const [code, cities] of codeToCities) {
    if (cities.size > 1) {
      conflicts.push(`${code}: ${[...cities].sort().join(" | ")}`);
      continue;
    }
    map[code] = [...cities][0];
  }

  conflicts.sort();
  return { map, conflicts, skippedNoMunicipality, rowCount };
}

/**
 * @param {Record<string, string>} map
 * @param {{ sourceUrl: string, generatedAt: string, rowCount: number, skippedNoMunicipality: number, conflictCount: number }} meta
 */
export function generateModuleSource(map, meta) {
  const keys = Object.keys(map).sort();
  const lines = keys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(map[k])},`);
  return `/** Generated by scripts/generate-airport-city-map.mjs — do not edit. */
export const AIRPORT_CITY_MAP_SOURCE = ${JSON.stringify(meta.sourceUrl)};
export const AIRPORT_CITY_MAP_GENERATED_AT = ${JSON.stringify(meta.generatedAt)};
export const AIRPORT_CITY_MAP_ROW_COUNT = ${meta.rowCount};
export const AIRPORT_CITY_MAP_KEY_COUNT = ${keys.length};
export const AIRPORT_CITY_MAP_CONFLICT_COUNT = ${meta.conflictCount};
export const AIRPORT_CITY_MAP_SKIPPED_NO_MUNICIPALITY = ${meta.skippedNoMunicipality};

/** @type {Readonly<Record<string, string>>} */
export const AIRPORT_CITY_MAP = {
${lines.join("\n")}
};

/** @param {string|null|undefined} code */
export function lookupAirportCity(code) {
  if (!code) return null;
  const key = String(code).trim().toUpperCase();
  if (!key) return null;
  return AIRPORT_CITY_MAP[key] ?? null;
}
`;
}

/**
 * @param {string} csvText
 * @param {{ sourceUrl?: string, generatedAt?: string }} [opts]
 * @param {Record<string, string>} [countryNames]
 */
export function buildModuleFromCsv(csvText, opts = {}, countryNames = {}) {
  const { map, conflicts, skippedNoMunicipality, rowCount } = buildMapFromCsv(
    csvText,
    countryNames,
  );
  const sourceUrl = opts.sourceUrl ?? OURAIRPORTS_CSV_URL;
  const generatedAt = opts.generatedAt ?? new Date().toISOString().slice(0, 10);
  const source = generateModuleSource(map, {
    sourceUrl,
    generatedAt,
    rowCount,
    skippedNoMunicipality,
    conflictCount: conflicts.length,
  });
  return { source, map, conflicts, keyCount: Object.keys(map).length };
}

async function fetchCsv(url) {
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`HTTP ${res.status} fetching ${url}`);
  }
  return res.text();
}

export async function generateAirportCityMap(outPath = defaultOutPath, csvText = null) {
  const text = csvText ?? (await fetchCsv(OURAIRPORTS_CSV_URL));
  const countriesText = await fetchCsv(OURAIRPORTS_COUNTRIES_CSV_URL);
  const countryHeader = parseCsvLine(countriesText.trim().split(/\r?\n/)[0]);
  const countryCodeIndex = countryHeader.indexOf("code");
  const countryNameIndex = countryHeader.indexOf("name");
  const countryNames = Object.create(null);
  for (const line of countriesText.trim().split(/\r?\n/).slice(1)) {
    if (!line.trim()) continue;
    const fields = parseCsvLine(line);
    const code = String(fields[countryCodeIndex] || "").trim().toUpperCase();
    const name = String(fields[countryNameIndex] || "").trim();
    if (code && name) countryNames[code] = name;
  }
  const { source, map, conflicts, keyCount } = buildModuleFromCsv(
    text,
    {},
    countryNames,
  );
  writeFileSync(outPath, source, "utf8");
  const byteSize = Buffer.byteLength(source, "utf8");
  return { outPath, keyCount, byteSize, conflicts };
}

const isMain =
  process.argv[1] &&
  fileURLToPath(import.meta.url) === join(process.argv[1]);

if (isMain) {
  const outArg = process.argv[2];
  const outPath = outArg ? join(process.cwd(), outArg) : defaultOutPath;
  generateAirportCityMap(outPath)
    .then(({ outPath: written, keyCount, byteSize, conflicts }) => {
      console.error(`Wrote ${written}`);
      console.error(`Keys: ${keyCount}, bytes: ${byteSize}`);
      if (conflicts.length > 0) {
        console.error(`Omitted ${conflicts.length} conflicting code(s):`);
        for (const c of conflicts.slice(0, 20)) {
          console.error(`  ${c}`);
        }
        if (conflicts.length > 20) {
          console.error(`  … and ${conflicts.length - 20} more`);
        }
      }
    })
    .catch((err) => {
      console.error(err);
      process.exit(1);
    });
}
